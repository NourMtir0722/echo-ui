"use client";

/**
 * The site's one theme, chosen anywhere and worn everywhere.
 *
 * The generator and the homepage swatches used to keep the seed in their own
 * React state — the generator scoped to a preview box, the homepage to itself
 * — and every other page re-emitted the default seed on load. So "pick
 * Sky, then go and look at the Switch" showed a default-coloured Switch.
 *
 * Now the seed lives here. Choosing one writes its generated CSS into a single
 * `<style id="echo-site-theme">` in <head>, after the layout's default block,
 * and saves it to localStorage. `THEME_BOOT_SCRIPT` (theme-boot.ts) puts the saved
 * block back before first paint on every page load, so a reseeded site never flashes
 * the default first. The site is a static export, so this has to happen in the
 * browser.
 */
import { useSyncExternalStore } from "react";
import { siteTheme } from "./site-theme";
import { DRAWN_ATTR, SEED_CHOSEN_ATTR, THEME_STORAGE_KEY as STORAGE_KEY, THEME_STYLE_ID as STYLE_ID } from "./theme-boot";
import { DEFAULT_SEED, isStyleName, lookOf, sameSeed, type Seed } from "./seeds";

export { DEFAULT_SEED, SEED_PRESETS, STYLE_PRESETS, sameSeed, type Seed } from "./seeds";

const HEX = /^#[0-9a-f]{6}$/i;

const isSeed = (v: unknown): v is Seed =>
  !!v &&
  typeof v === "object" &&
  (["accent", "chassis", "paper"] as const).every(
    (k) => typeof (v as Record<string, unknown>)[k] === "string" && HEX.test((v as Record<string, string>)[k]!),
  ) &&
  // A style that's no longer published is no choice: the site falls back to Echo's.
  ((v as Seed).style === undefined || isStyleName((v as Seed).style));

/** The visitor's choice, or null until they make one. */
let current: Seed | null = null;
let read = false;
const listeners = new Set<() => void>();

function readChoice(): Seed | null {
  try {
    const v = JSON.parse(window.localStorage.getItem(STORAGE_KEY) ?? "null") as { seed?: unknown } | null;
    if (v && isSeed(v.seed)) return v.seed;
  } catch {
    /* storage blocked or corrupt — no choice, then */
  }
  return null;
}

function paint(css: string | null) {
  let el = document.getElementById(STYLE_ID);
  if (css === null) {
    el?.remove();
    return;
  }
  if (!el) {
    el = document.createElement("style");
    el.id = STYLE_ID;
    document.head.appendChild(el);
  }
  el.textContent = css;
}

/**
 * Wear a choice: its CSS (none for the default seed, which the layout already
 * emits) and the mark on <html>. A seed that names a style wears the style's
 * whole look under its colours: drawn or molded, its corners and its type.
 */
function wear(seed: Seed) {
  const look = lookOf(seed);
  paint(sameSeed(seed, DEFAULT_SEED) ? null : siteTheme(look).css);
  document.documentElement.setAttribute(SEED_CHOSEN_ATTR, "");
  document.documentElement.toggleAttribute(DRAWN_ATTR, look.render === "drawn");
}

function apply(seed: Seed) {
  wear(seed);
  const css = sameSeed(seed, DEFAULT_SEED) ? "" : (document.getElementById(STYLE_ID)?.textContent ?? "");
  try {
    // Saved even when it's the default: picking purple on a page that opens on Sky is a choice.
    window.localStorage.setItem(STORAGE_KEY, JSON.stringify({ seed, css }));
  } catch {
    /* storage blocked — the theme still applies until the tab closes */
  }
}

/** Relights the whole site and remembers it. */
export function setSiteSeed(seed: Seed) {
  current = seed;
  apply(seed);
  listeners.forEach((l) => l());
}

/*
 * The saved CSS was generated by whatever version of the site saved it. Once
 * per page load, regenerate it from the saved seed, so a change to what the
 * theme emits (the brand variables, say) reaches returning visitors too.
 */
let refreshed = false;

// Another tab changed the theme: follow it, so two open tabs never disagree.
function onStorage(e: StorageEvent) {
  if (e.key !== STORAGE_KEY) return;
  current = readChoice();
  if (current) wear(current);
  else {
    paint(null);
    document.documentElement.removeAttribute(SEED_CHOSEN_ATTR);
    document.documentElement.removeAttribute(DRAWN_ATTR);
  }
  listeners.forEach((l) => l());
}

function subscribe(listener: () => void) {
  if (!refreshed) {
    refreshed = true;
    const choice = getSnapshot();
    if (choice) apply(choice);
  }
  if (listeners.size === 0) window.addEventListener("storage", onStorage);
  listeners.add(listener);
  return () => {
    listeners.delete(listener);
    if (listeners.size === 0) window.removeEventListener("storage", onStorage);
  };
}

const getSnapshot = () => {
  if (!read) {
    read = true;
    current = readChoice();
  }
  return current;
};
const getServerSnapshot = () => null;

/** The visitor's saved choice, read now: null if they never picked one. */
export const chosenSiteSeed = (): Seed | null => getSnapshot();

/**
 * The site's seed, and the setter that relights every page. Until the visitor
 * picks one, it's the page's own opening colour (`opening`), or the default.
 */
export function useSiteSeed(opening: Seed = DEFAULT_SEED): [Seed, (seed: Seed) => void] {
  return [useSyncExternalStore(subscribe, getSnapshot, getServerSnapshot) ?? opening, setSiteSeed];
}
