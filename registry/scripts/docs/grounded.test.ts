/* ------------------------------------------------------------- corpora --- */

function filesUnder(dir: string, ext: RegExp, skip: (path: string) => boolean = () => false): string[] {
  if (!existsSync(dir)) return [];
  const out: string[] = [];
  for (const entry of readdirSync(dir)) {
    const path = join(dir, entry);
    if (skip(path)) continue;
    if (statSync(path).isDirectory()) {
      if (entry === "node_modules" || entry.startsWith(".next")) continue;
      out.push(...filesUnder(path, ext, skip));
    } else if (ext.test(entry)) out.push(path);
  }
  return out;
}

const read = (files: string[]) => files.map((f) => readFileSync(f, "utf8")).join("\n");

let baseUiText: string | undefined;
function baseUi(): string {
  baseUiText ??= read(filesUnder(dirname(require.resolve("@base-ui/react/package.json")), /\.m?js$/));
  return baseUiText;
}

const registryItems = new Map(
  (JSON.parse(readFileSync(join(registryRoot, "registry.json"), "utf8")) as {
    items: { name: string; dependencies?: string[]; registryDependencies?: string[] }[];
  }).items.map((i) => [i.name, i]),
);
/** Meta names of the echo-ui-core modules: what an item gets from `echo-ui-core`. */
const coreItems = Object.entries(META_DIRS)
  .filter(([, dir]) => dir in CORE_DIRS)
  .map(([name]) => name);
const dirOf = new Map<string, string>(Object.entries(META_DIRS));

/**
 * An item's shipped source, and the source of every Echo item it pulls in —
 * never its meta.ts. `own` is just the item's own folder, for numbers.
 */
function itemCorpus(name: string): { all: string; own: string } {
  const seen = new Set<string>();
  const visit = (n: string) => {
    if (seen.has(n)) return;
    seen.add(n);
    const item = registryItems.get(n);
    for (const dep of item?.registryDependencies ?? []) visit(dep.replace(/^@echo\//, ""));
    // echo-ui-core stands in for the theme/sound/motion items it replaced.
    if (item?.dependencies?.includes("echo-ui-core")) coreItems.forEach(visit);
  };
  visit(name);
  // The item's examples and usage count too: test A compiles them against the
  // real component, so a prop they use is checked code, not a claim.
  const meta = ALL_METAS.find((m) => m.name === name) as (AnyMeta & MetaDocsFields) | undefined;
  const compiled = [...(meta?.examples ?? []).map((e) => e.code), meta?.usage?.code ?? "", meta?.usage?.imports ?? ""].join("\n");
  const text = compiled + "\n" + read(
    [...seen].flatMap((n) => {
      const dir = dirOf.get(n);
      return dir ? filesUnder(itemDir(dir), /\.(tsx?|css)$/, (p) => /meta\.ts$|\.test\.ts$/.test(p)) : [];
    }),
  );
  // Numbers are checked against the item's own folder only: a default like a
  // delay is set there, and its dependencies hold enough other numbers
  // (motion.ts alone has 300, 400, 600…) to vouch for a wrong one.
  const ownDir = dirOf.get(name);
  const own = ownDir ? read(filesUnder(itemDir(ownDir), /\.(tsx?|css)$/, (p) => /meta\.ts$|\.test\.ts$/.test(p))) : "";
  return { all: text.includes("@base-ui/react") ? `${text}\n${baseUi()}` : text, own };
}

let everythingText: string | undefined;
/**
 * For guides: all the code in the repo (no metas, no guides), including the
 * CLI and the registry client the guides describe. Every flag a guide names
 * is Echo's own, so the corpus that vouches for them is Echo's own source.
 */
function everything(): string {
  everythingText ??= read([
    ...filesUnder(join(registryRoot, "src"), /\.(tsx?|css)$/, (p) => /meta\.ts$|\.test\.ts$|__snippets__/.test(p)),
    ...filesUnder(coreRoot, /\.(tsx?|css)$/, (p) => /\.test\.ts$/.test(p)),
    ...filesUnder(join(repoRoot, "mcp/src"), /\.ts$/, (p) => /\.test\.ts$/.test(p)),
    ...filesUnder(join(repoRoot, "packages/cli/src"), /\.ts$/, (p) => /\.test\.ts$/.test(p)),
    ...filesUnder(join(repoRoot, "packages/client/src"), /\.ts$/, (p) => /\.test\.ts$/.test(p)),
    ...filesUnder(join(repoRoot, "apps/www/components"), /\.(tsx?|css)$/),
    ...filesUnder(join(repoRoot, "apps/www/app"), /\.(tsx?|css)$/),
  ]).concat("\n", baseUi());
  return everythingText;
}

/* ------------------------------------------------------------ claims --- */

/** Code-like words inside backticks: identifiers, dotted names, dashed names, paths. */
function terms(text: string): string[] {
  const out: string[] = [];
  for (const [, span] of text.matchAll(/`([^`]+)`/g)) {
    const whole = span!.trim();
    if (whole in EXTERNAL) continue;
    for (const [t] of whole.matchAll(/[A-Za-z_$@./][\w$@./-]*/g)) {
      const term = t.replace(/[.,:;]+$/, "");
      if (term.length < 2 || /[-*/]$/.test(term) || /^\.+$/.test(term)) continue;
      if (term in EXTERNAL) continue;
      out.push(term);
    }
  }
  return out;
}

/** "400ms" → "400"; the number has to be in the code. */
const durations = (text: string) => [...text.matchAll(/\b(\d+(?:\.\d+)?)\s?ms\b/g)].map((m) => m[1]!);

interface Claim {
  where: string;
  text: string;
}

function itemClaims(meta: AnyMeta): Claim[] {
  const m = meta as AnyMeta & MetaDocsFields & { propsNote?: string };
  const claims: Claim[] = [{ where: "description", text: m.description }];
  if (m.propsNote) claims.push({ where: "propsNote", text: m.propsNote });
  for (const p of describeProps(m.props)) if (p.description) claims.push({ where: `prop ${p.name}`, text: p.description });
  for (const ex of m.examples) claims.push({ where: `example "${ex.title}"`, text: ex.description });
  for (const a of m.antiPatterns) claims.push({ where: "anti-pattern", text: a });
  for (const a of m.a11y ?? []) claims.push({ where: "a11y", text: a });
  for (const s of m.sound ?? []) claims.push({ where: "sound", text: s });
  if (m.motion) {
    claims.push({ where: "reducedMotion", text: m.motion.reducedMotion });
    for (const t of m.motion.tokens) claims.push({ where: "motion token", text: `\`${t}\`` });
  }
  return claims;
}

/** A dotted chain (`values.roles.accent`) is grounded when each link is. */
const found = (term: string, corpus: string) =>
  corpus.includes(term) || (term.includes(".") && !term.includes("/") && term.split(".").every((part) => !part || corpus.includes(part)));

function ungrounded(claims: Claim[], corpus: string, numbers = corpus): string[] {
  const out: string[] = [];
  for (const { where, text } of claims) {
    for (const term of terms(text)) if (!found(term, corpus)) out.push(`${where}: \`${term}\``);
    for (const n of durations(text)) if (!new RegExp(`\\b${n.replace(".", "\\.")}\\b`).test(numbers)) out.push(`${where}: ${n}ms`);
  }
  return [...new Set(out)];
}

test("F: every code term in an item's docs exists in the code it ships", () => {
  const failures: string[] = [];
  for (const meta of ALL_METAS) {
    const { all, own } = itemCorpus(meta.name);
    const bad = ungrounded(itemClaims(meta), all, own);
    if (bad.length) failures.push(`${meta.name}\n      ${bad.join("\n      ")}`);
  }
  assert.deepEqual(failures, [], `\nNot found in the item's own code — check the source, then fix the prose:\n  ${failures.join("\n  ")}\n`);
});

/** Guide prose, without fenced code blocks (examples are the reader's code, not claims about ours). */
function guideProse(): { page: string; text: string }[] {
  const dir = resolve(repoRoot, "apps/www/app/docs/(guides)");
  const pages = ["content.mdx", ...readdirSync(dir).filter((d) => existsSync(join(dir, d, "content.mdx"))).map((d) => `${d}/content.mdx`)];
  return pages.map((page) => ({
    page,
    text: readFileSync(join(dir, page), "utf8")
      .replace(/^```[\s\S]*?^```/gm, "")
      .replace(/^(import|export) .*$/gm, ""),
  }));
}

test("F: every code term on a guide page exists in the codebase", () => {
  const corpus = everything();
  const failures = guideProse()
    .map(({ page, text }) => ({ page, bad: ungrounded([{ where: page, text }], corpus) }))
    .filter((r) => r.bad.length)
    .map((r) => r.bad.join("\n  "));
  assert.deepEqual(failures, [], `\nNot found in the code:\n  ${failures.join("\n  ")}\n`);
});

test("F: EXTERNAL only lists terms the docs actually use", () => {
  const all = [
    ...ALL_METAS.flatMap((m) => itemClaims(m).map((c) => c.text)),
    ...guideProse().map((g) => g.text),
  ].join("\n");
  const unused = Object.keys(EXTERNAL).filter((t) => !all.includes(t));
  assert.deepEqual(unused, [], "remove these from EXTERNAL — nothing uses them any more");
});
