/**
 * Docs freshness test F: the docs are written from the code, not from memory.
 *
 * A sentence can be wrong in ways no type checker sees — "the tooltip opens
 * immediately on focus", "the trigger has aria-haspopup", "the file is saved
 * as echo-muted". What those sentences have in common is a term in backticks
 * that names something in the code. This test takes every such term in the
 * user-facing docs and requires it to exist in the code the item actually
 * ships:
 *
 * - **An item's docs** (meta.ts prose: description, prop descriptions,
 *   examples' descriptions, anti-patterns, a11y, motion, sound) are checked
 *   against that item's own source files, the Echo items it depends on, and —
 *   when it wraps Base UI — Base UI's own code, which is where roles and ARIA
 *   attributes like `aria-selected` really come from. The meta.ts itself is
 *   NOT evidence: a claim cannot vouch for itself.
 * - **Guide pages** (MDX) are checked against the whole codebase and the
 *   CLI and client they describe.
 *
 * Durations quoted with a unit ("400ms") must appear as a number in that code
 * too. When this test fails, the fix is to go and read the code: either the
 * term is wrong (fix the prose), or it names something outside the code that
 * a reader genuinely needs — then it goes in EXTERNAL, with the reason.
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { existsSync, readFileSync, readdirSync, statSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, resolve } from "node:path";

